/** اختيار حتمي يتغير يوميًا */
export function pickByDate<T>(arr: T[], dateISO: string, salt = 0): T {
  const [y, m, d] = dateISO.split('-').map(Number);
  const dayNumber = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  return arr[(((dayNumber + salt) % arr.length) + arr.length) % arr.length];
}

